    m = re.search(r"window\.DASHBOARD_DATA\s*=\s*(\{.*\});?\s*$", s, re.S)
    if not m:
        return []
    d = json.loads(m.group(1))
    items = []
    for node in ("ashare", "us"):
        sub = d.get(node, {})
        for k in ("bullNews", "bearNews", "macroNews", "intlNews", "bankViews"):
            for it in (sub.get(k) or []):
                title = it.get("title", "")
                src = it.get("source", "")
                if title:
                    items.append(f"{title}（源:{src}）")
    return items


