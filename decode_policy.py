# ---------------- 1) 发文主体 ----------------
def decode_issuer(text):
    t = text or ""
    # 联名：同时含 中共中央/党中央 + 国务院
    if re.search(r"(中共中央|党中央)", t) and re.search(r"国务院", t):
        return 5, "中共中央+国务院(联名)", "joint_top"
    if re.search(r"(中共中央|党中央|政治局|中央财经委|深改委|全国人大|人大常委会)", t):
        return 5, "党中央/全国人大(顶层)", "party_top"
    if re.search(r"国务院", t):
        return 4, "国务院", "state_council"
    if re.search(r"(央行|中国人民银行)", t):
        return 3, "央行(金融加权)", "pboc"
    if re.search(r"(多部门|若干部门|部委联合|多部委|联合印发|会同有关部门|等\s*\d+\s*部门|等部门|相关部委)", t):
        return 3, "部委联合", "joint_ministry"
    for kw in ["发改委", "发展改革委", "工信部", "工业和信息化部", "财政部", "商务部",
               "国资委", "证监会", "金融监管总局", "农业农村部", "国家能源局", "统计局",
               "海关总署", "住建部", "生态环境部", "人社部", "人力资源社会保障部", "卫健委"]:
        if kw in t:
            return 2, kw, "single_ministry"
    if re.search(r"(新华社|人民日报|财联社|证券时报|中国证券报|第一财经|华尔街见闻|"
                 r"中信|华泰|高盛|摩根|特朗普|白宫|美联储|美国|欧盟|日本|"
                 r"世贸组织|世气组织|路透|彭博)", t):
        return 0, "媒体/券商/外国(非政策源)", "non_policy"
    return 1, "未识别", "unknown"


# ---------------- 2) 文种 ----------------
DOC_TYPES = [
    ("决定", 1.00),
    ("法", 0.95), ("法律", 0.95), ("条例", 0.90),
    ("纲要", 0.85), ("规划", 0.85), ("规划纲", 0.85),
    ("方案", 0.70), ("行动方案", 0.70),
    ("意见", 0.55),
    ("通知", 0.35),
    ("公告", 0.30),
    ("措施", 0.60),
    ("指南", 0.20),
]
DOC_DECAY = {"决定": 30, "法": 45, "纲要": 30, "规划": 30, "方案": 20,
             "意见": 14, "通知": 5, "公告": 5, "措施": 15, "指南": 5}


def decode_doc_type(text):
    t = text or ""
    # 印发通知 + 附件主题词：承载规划的印发通知权重随附件，避免错判成弱通知
    m = re.search(r"印发(.+?)的通知", t)
    if m:
        carried = m.group(1)
        for name, w in DOC_TYPES:
            if name in carried:
                return name + "（印发通知承载）", w, carried
        return "通知(操作类·承载未识别文种)", 0.35, None
    for name, w in DOC_TYPES:
        if name in t:
            return name, w, None
    return "无文种(操作/事件)", 0.40, None


# ---------------- 3) 量化指标 ----------------
def decode_indicator(text):
    t = text or ""
    binding = "directional"
    if re.search(r"(约束性|必须|硬性|硬指标|强制|刚性|底线|硬性任务|确保|坚决|硬性约束|必须完成|刚性兑现|底线指标|明确要求)", t):
        binding = "hard"
    elif re.search(r"(预期性|力争|努力|争取|到.+?左右|约.+?左右|目标导向|适度|目标突破|力争突破|目标达到|突破.+?目标)", t):
        binding = "soft"
    nums = re.findall(r"(\d+(?:\.\d+)?\s*(?:万亿|亿|万|%|％|倍|个百分点))", t)
    years = re.findall(r"(202[5-9]|203[0-5]|十四五|十五五)", t)
    return binding, nums, years


