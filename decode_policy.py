MONETARY_KW = r"(降准|降息|逆回购|MLF|SLF|LPR|存款准备金|利率|流动性|公开市场操作|OMO|麻辣粉|酸辣粉|再贷款|再贴现|中期借贷便利|汇率|人民币汇率|外汇风险|贬值|升值)"
FISCAL_KW = r"(财政部|税务总局|国债|专项债|减税降费|财政补贴|转移支付|财政贴息)"
INDUSTRIAL_KW = r"(发改委|工信部|商务部|国资委|产业|制造强国|专精特新|供应链安全|设备更新)"


def decode_signal_class(text, issuer_name=""):
    """把政策信号归到 货币政策 / 财政 / 产业 / 其他 四类。

    央行操作（降准/降息/逆回购/MLF/LPR…）是即时、全域流动性信号，与财政/产业政策
    传导机制不同，单独成类便于策略引擎差异化处理（货币政策更看估值/流动性，
    产业政策更看盈利/赛道）。"""
    t = text or ""
    if re.search(r"(央行|中国人民银行)", t) and re.search(MONETARY_KW, t):
        return "货币政策"
    if re.search(FISCAL_KW, t):
        return "财政"
    if re.search(INDUSTRIAL_KW, t) or re.search(r"工信部等|发改委等|商务部等", t):
        return "产业"
    return "其他"


# ---------------- 复合评分 ----------------
def policy_score(text):
    issuer_tier, issuer_name, _ = decode_issuer(text)
    doc_name, doc_w, _ = decode_doc_type(text)
    binding, nums, years = decode_indicator(text)
    sectors = decode_sector(text)
    time_factor, time_notes = decode_time_compression(text)
    signal_class = decode_signal_class(text, issuer_name)

    issuer_norm = issuer_tier / 5.0
    binding_factor = 1.0 + (0.15 if binding == "hard" else 0.05 if binding == "soft" else 0.0)
    joint_boost = 1.0
    # 顶层联名意见（中共中央+国务院）：按用户框架「联名意见信号等级相当高」→ 顶 S 级。
    # 把文种下限抬到 0.98 并给 1.15 联名加权，确保联名意见即便无硬指标也稳进 S。
    if issuer_tier == 5 and doc_name.startswith("意见"):
        doc_w = max(doc_w, 0.98)
        doc_name += "（顶层联名→顶档）"
        joint_boost = 1.15
    if signal_class == "货币政策":
        # 央行操作（降准/降息/逆回购/MLF…）是即时的全域流动性决策信号，
        # 功能上等同「决定」级动作，文种权重抬到 0.80 并给 1.12 即时影响加权。
        doc_w = max(doc_w, 0.85)
        monetary_boost = 1.12
    else:
        monetary_boost = 1.0
    raw = issuer_norm * doc_w * binding_factor * time_factor * joint_boost * monetary_boost
    score = int(min(raw, 1.4) / 1.4 * 100)
    tier = "S" if score >= 80 else "A" if score >= 60 else "B" if score >= 40 else "C"
    decay = DOC_DECAY.get(doc_name[:2], 10)
    return {
        "issuer": f"{issuer_name}(t{issuer_tier})",
        "docType": doc_name,
        "binding": binding,
        "signalClass": signal_class,
        "targets": nums + ([f"年:{y}" for y in years]),
        "sectors": sectors,
        "timeFactor": time_factor,
        "score": score, "tier": tier, "decayDays": decay,
    }


