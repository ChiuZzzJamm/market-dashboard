def decode_sector(text):
    t = text or ""
    out = []
    for kw, secs in SECTOR_LEXICON.items():
        if kw in t:
            out.extend(secs)
    return list(dict.fromkeys(out))


# ---------------- 5) 时间压缩 ----------------
def decode_time_compression(text):
    t = text or ""
    factor = 1.0
    notes = []
    if re.search(r"(即日起|立即|马上|当日|立马)", t):
        factor += 0.30; notes.append("即日执行+0.3")
    elif re.search(r"(年底前|本月底|本季末|三个月内|\d+月\d+日前|一周内|两周内)", t):
        factor += 0.20; notes.append("短期窗口+0.2")
    elif re.search(r"(202[5-9]年|203[0-5]年|十四五|十五五)", t):
        factor += 0.05; notes.append("有时间表+0.05")
    n_sub = re.search(r"(\d+)\s*(?:条|项|方面|举措|措施)", t)
    if n_sub:
        k = int(n_sub.group(1))
        if k >= 10:
            factor += 0.10; notes.append(f"细分{k}条+0.1")
    if re.search(r"若干", t):
        factor += 0.10; notes.append("若干条+0.1")
    return round(min(factor, 1.4), 2), notes


