    for pool in ('confirmed', 'watching'):
        for it in m.get(pool) or []:
            stats['c' if pool == 'confirmed' else 'w'] += 1
            sec = it.get('sector') or ''
            bull, bear = news_for(sec)
            bull = _dedup(bull)
            bear = _dedup(bear)
