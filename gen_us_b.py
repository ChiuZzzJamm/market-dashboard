def mk_stocks(key):
    g = T[key]; seen = {}; out = []
    for role in ('L', 'C', 'S'):
        for c in g[role]:
            assert c in NAMES, c
            seen[c] = seen.get(c, 0) + 1
            out.append({'code': c, 'name': NAMES[c],
                        'note': ('%s·%s' % (TAG[role], DESC.get(c, '')))[:20]})
    assert len(out) == 8, (key, len(out))
    assert len({s['code'] for s in out}) == 8, key
    return out

def imp(theme, key):
    return {'theme': theme, 'stocks': mk_stocks(key)}

