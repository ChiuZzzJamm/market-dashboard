def selfcheck(d):
    """写回前机械自检：reason 长度/标题、四类前缀与配比、组内唯一、60/00 主板、来源白名单。"""
    import re
    import news_sources as NS
    wl = NS.WHITELIST if hasattr(NS, 'WHITELIST') else None
    err = []
    us = d['us']
    tot = 0
    for s in us.get('sectorsUp', []) + us.get('sectorsDown', []):
        r = s.get('reason') or {}
        t, dt = r.get('title', ''), r.get('detail', '')
        tot += len(t) + len(dt)
        if len(t) > 26:
            err.append('title>26 %s(%d)' % (s.get('name'), len(t)))
        if not (60 <= len(dt) <= 110):
            err.append('detail 越界 %s(%d)' % (s.get('name'), len(dt)))
        dc = s.get('deduce') or {}
        if not dc.get('counter'):
            err.append('deduce 缺 counter %s' % s.get('name'))
        if dc.get('conf') not in ('高确信', '中等确信', '推测', '直觉'):
            err.append('conf 非枚举 %s' % s.get('name'))
        for k in ('main', 'counter'):
            if str(dc.get(k, '')).startswith(('主推：', '反证：')):
                err.append('前缀 %s.%s' % (s.get('name'), k))
    if tot > 1800:
        err.append('reason 总长 %d>1800' % tot)
    for k in ('bullNews', 'bearNews', 'macroNews', 'intlNews', 'bankViews'):
        for i, it in enumerate(us.get(k) or []):
            tag = '%s[%d]%s' % (k, i, it.get('title', '')[:14])
            if wl is not None and it.get('source') not in wl:
                err.append('来源不在白名单 %s: %s' % (tag, it.get('source')))
            dc = it.get('deduce') or {}
            if not dc.get('counter'):
                err.append('deduce 缺 counter %s' % tag)
            if dc.get('conf') not in ('高确信', '中等确信', '推测', '直觉'):
                err.append('conf 非枚举 %s' % tag)
            imps = it.get('impacts') or []
            if not (1 <= len(imps) <= 4):
                err.append('impacts 组数越界 %s(%d)' % (tag, len(imps)))
            for g in imps:
                st = g.get('stocks') or []
                if len(st) != 8:
                    err.append('组内非8只 %s/%s(%d)' % (tag, g.get('theme'), len(st)))
                if len({x['code'] for x in st}) != len(st):
                    err.append('组内重复 %s/%s' % (tag, g.get('theme')))
                cats = {}
                for x in st:
                    if not re.match(r'^(60|00)', x['code']):
                        err.append('非主板 %s %s' % (tag, x['code']))
                    note = x.get('note', '')
                    cat = next((c for c in ('板块龙头', '相关概念', '小盘人气', '断板反包')
                                if note.startswith(c)), '?')
                    cats[cat] = cats.get(cat, 0) + 1
                if '断板反包' in cats:
                    err.append('断板位非0(A股休市) %s/%s' % (tag, g.get('theme')))
                elif cats != {'板块龙头': 2, '相关概念': 2, '小盘人气': 4}:
                    err.append('配比不符 %s/%s %s' % (tag, g.get('theme'), cats))
                if k in ('macroNews', 'intlNews', 'bankViews') and g.get('horizon') not in ('长线', '短线'):
                    err.append('缺 horizon %s/%s' % (tag, g.get('theme')))
    # 3.87 跨节同主题
    from collections import Counter
    th = Counter()
    for k in ('bullNews', 'bearNews', 'macroNews', 'intlNews', 'bankViews'):
        for it in us.get(k) or []:
            for g in it.get('impacts') or []:
                th[g.get('theme')] += 1
    cross = {a: b for a, b in th.items() if b > 1}
    print('[跨节主题] 重复 theme:', cross or '无')
    if err:
        print('[自检失败]')
        for e in err:
            print('  -', e)
        raise SystemExit(1)
    print('[自检通过] reason总长=%d' % tot)


