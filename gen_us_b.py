def news_item(sector, title, summary, source, *rest, **kw):
    """兼容两种写法：news_item(.., impacts, deduce) 与 news_item(.., direction, impacts, deduce)。"""
    direction = kw.get('direction')
    if rest and isinstance(rest[0], str):
        direction, rest = rest[0], rest[1:]
    it = {'sector': sector, 'title': title, 'summary': summary, 'source': source,
          'time': DATE, 'impacts': rest[0]}
    if direction is not None:
        it['direction'] = direction
    it['deduce'] = rest[1]
    return it

