        {"tag":"事件驱动","text":c1,"eliminate":"若%s未兑现则%s题材降温"%(trigger,theme)},
        {"tag":"资金驱动","text":c2,"eliminate":"若%s量能跌破万亿则反弹中止，转为防御。"%theme}
