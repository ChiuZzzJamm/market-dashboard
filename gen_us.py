def alloc(theme):
    info = THEME[theme]
    matched = []
    for bk in info['boards']:
        for s in scan.get(bk, []):
            if s['code'] in BLACKLIST: continue
            matched.append(s)
    N = min(len(matched), 5)
    table = {5:(1,1,1,5),4:(2,1,1,4),3:(2,2,1,3),2:(2,2,2,2),1:(2,2,3,1),0:(2,2,4,0)}
    nL,nC,nS,nD = table[N]
    pools = info['pools']
    used = set(); stocks=[]
    def pick(pool, n, prefix):
        out=[]
        for code,name,brief in pool:
            if len(out)>=n: break
            if code in ('300','688','暂占位') or code.startswith(('300','688','301','302','4','8','92')): continue
            if code in BLACKLIST: continue
            if code in used: continue
            used.add(code); out.append({'code':code,'name':name,'note':prefix+brief})
        return out
    L = pick(pools['龙头'], nL, '板块龙头·')
    C = pick(pools['概念'], nC, '相关概念·')
    D=[]
    for s in matched[:N]:
        if s['code'] in used: continue
        used.add(s['code']); D.append({'code':s['code'],'name':s['name'],'note':'断板反包·'+s['form']})
    S = pick(pools['小盘'], nS, '小盘人气·')
    stocks = L+C+S+D
    fb = [['600000','浦发银行','银行'],['601398','工商银行','大行'],['601988','中国银行','大行'],['600028','中国石化','石化'],['601857','中国石油','油气'],['600036','招商银行','银行']]
    while len(stocks)<8:
        added=False
        for code,name,brief in fb:
            if code not in used and len(stocks)<8:
                used.add(code); stocks.append({'code':code,'name':name,'note':'小盘人气·'+brief}); added=True; break
        if not added: break
    return stocks, N

def build_impacts(theme, horizon):
    stocks, N = alloc(theme)
    return [{'theme':theme,'stocks':stocks,'horizon':horizon}], N

