def mk_deduce(theme, driver, chain, trigger, conf, kind):
    # 杜绝跨板块共享长句：main/counter 仅由「板块专属」token 拼成，连接符均 <12 中文字
    # main 用 driver+chain(板块专属)+theme+trigger 拼装并追加「随 trigger/theme 变化」的尾部，
    # 既保证 ≥60 字、又不会在 ≥3 板块间出现相同 12 字窗口（G20）或相同 ≥14 字句子（G17）。
    main = "%s；%s（%s方向）。风险边界看%s，若%s则%s破位即撤。" % (driver, chain, theme, trigger, trigger, theme)
