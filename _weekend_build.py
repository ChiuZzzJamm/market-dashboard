# ---------------------------------------------------------------- 四类分层（N 分层表）
TIERS = {5: (1, 1, 1), 4: (2, 1, 1), 3: (2, 2, 1), 2: (2, 2, 2), 1: (2, 2, 3), 0: (2, 2, 4)}


def build8(N, leaders, concepts, smalls, board):
    """按 N 分层组装恰好 8 只：龙头/概念/小盘 = TIERS[N]，断板 = min(N,5) 全部取自 pool[board]。
    leaders/concepts/smalls 长度须 >= TIERS[N][i]，不足的用尽；断板位不足则从小盘补足。"""
    L, C, X = TIERS[N]
    nD = min(N, 5)
    # 断板池已占用的 code（龙头/概念/小盘不得与断板重复）
    used = set()
    if board:
        for k in range(min(N, 5)):
            it = db(board, k)
            if it:
                used.add(it[0])

    def _take(lst, n):
        out, i = [], 0
        while len(out) < n and i < len(lst):
            if lst[i][0] not in used and lst[i][0] not in {x[0] for x in out}:
                out.append(lst[i])
            i += 1
        if len(out) < n:
            raise SystemExit(f'{board} 池内可用标的不足：need={n} have={len(out)}')
        return out

    leaders = _take(leaders, L)
    concepts = _take(concepts, C)
    smalls_all = list(smalls)
    st = []
    for i in range(L):
        c, _sfx = leaders[i]
        used.add(c)
        st.append(('板块龙头', c, sname(c), _sfx))
    for i in range(C):
        c, _sfx = concepts[i]
        used.add(c)
        st.append(('相关概念', c, sname(c), _sfx))
    # 断板股先从池取，剩余小盘位用 smalls 补
    need_x = X
    smalls = list(smalls)
    ds = []
    for k in range(nD):
        it = db(board, k)
        if it is None:
            break
        ds.append(it)
    nD = len(ds)
    # 若池内不足 5，TIERS 需要重算：断板实到 nD，小盘补足
    short = nD - min(N, 5)
    need_x = X + max(0, -short)  # 池内少于 N 时 X 不变（TIERS 已按 N 算）
    while len(smalls) < need_x:
        raise SystemExit(f'小盘股不足：board={board} need={need_x} have={len(smalls)}')
    xs = _take(smalls_all, need_x)
    for i in range(need_x):
        c, _sfx = xs[i]
        st.append(('小盘人气', c, sname(c), _sfx))
    for c, n, f in ds:
        st.append(('断板反包', c, n, f))
    # 兜底：不足 8 则补，>8 则截断（保持四类顺序）
    if len(st) < 8:
        raise SystemExit(f'build8 不足8：board={board} got={len(st)}')
    st = st[:8]
    return st


def mk(stocks):
    """[(cat,code,name,extra)] -> impacts 里的 stocks 列表。"""
    out = []
    for cat, code, name, extra in stocks:
        note = cat
        if cat == '断板反包':
            note = f'断板反包·{extra}'
        else:
            note = f'{cat}·{extra}'
        out.append({'code': code, 'name': name, 'note': note[:28]})
    return out


