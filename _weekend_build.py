def ex(code, cat):
    """按最近收盘生成退出三件套。"""
    p = px(code)
    if p is None:
        return {'stop': None, 'target': None,
                'falsify': '第 4-6 日仍不收复 MA5 且量能未放大——形态失败，视为假突破'}
    import math as _m
    if cat == '断板反包':
        stop = round(p * 0.975, 2)
        basis = '最近收盘 −2.5%（断板反包形态位）'
        falsify = '放量跌破断板日最低价，或反包日冲高回落收阴——形态失败，无条件离场'
    else:
        stop = round(p * 0.97, 2)
        basis = '最近收盘 −3%（机械候选，无形态位）'
        falsify = '次日收阴且跌破前一日最低价——情绪退潮，不追高'
    return {'stop': stop, 'target': round(p * 1.1, 2), 'falsify': falsify, 'stopBasis': basis}


