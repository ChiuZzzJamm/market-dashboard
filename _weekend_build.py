def grp(spec, N, theme, horizon=None):
    """按 spec + N 分层生成一个 impact 组（恰好 8 只）。"""
    ds = []
    if spec.get('db'):
        for k in range(min(N, 5)):
            it = db(spec['db'], k)
            if it:
                ds.append(it)
    stocks = build8(N, spec['L'], spec['C'], spec['X'], spec['db'])
    g = {'theme': theme, 'stocks': mk(stocks)}
    if horizon:
        g['horizon'] = horizon
    return g


