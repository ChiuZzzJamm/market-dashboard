def kline_note(e):
    """按当日涨跌幅生成一句克制描述（只作背景交代，不作利好/利空依据）。"""
    pct = e.get('pct')
    if pct is None:
        return '最新交易日收盘数据完整'
    if pct >= 9.9:
        return '最新交易日再度封涨停'
    if pct >= 5:
        return '最新交易日收涨约%.1f%%' % pct
    if pct >= 1:
        return '最新交易日小幅收涨约%.1f%%' % pct
    if pct > -1:
        return '最新交易日基本收平（%.1f%%）' % pct
    if pct > -5:
        return '最新交易日收跌约%.1f%%' % abs(pct)
    if pct > -9.9:
        return '最新交易日跌停附近收盘（%.1f%%）' % pct
    return '最新交易日跌停收盘'


def build_story(e, board):
    """逐只 story。

    G17 防模板复读：① 板块句统一「个股名 + 板块名 + 该股在该板块中的定位」开头，
    使每只的板块句文本唯一（否则同板块 ≥3 只共用一句会被判模板复读）；
    ② 尾句按个股差异化（按代码分散到 4 组措辞），不共用同一句。
    """
    _, b_msg, i_msg, note = board
    n, c = e['name'], e['code']
    if '{n}' not in b_msg and '{c}' not in b_msg:
        b = '%s所在的%s板块，%s' % (n, e['sector'], b_msg)
    else:
        b = b_msg.format(n=n, c=c, z=e.get('ztDate', ''))
    i = i_msg.format(n=n, c=c, z=e.get('ztDate', ''), kline_note=kline_note(e))
    tails = (
        '后续需以{n}所在细分方向的正式落地信号为准，目前该股无新公告可供确认。',
        '对{n}而言，消息面的验证点在于上述产业信号的兑现节奏，暂无个股级跟进。',
        '{n}的下一验证点是该方向的落地公告或招标进度，在出现前维持现有判断。',
        '{n}暂无个股级催化，判断依据完全来自板块层面的上述消息。',
    )
    tail = tails[int(c) % len(tails)].format(n=n)
    story = '【板块消息】%s【个股消息】%s%s' % (b, i, tail)
    return story, note


def adjust_prob(e, board, pool):
    """R98k 基线 + R89 隔夜依据微调。

    基线区间按**复核后的 sentiment** 取（脚本原值可能来自改判前的方向，不能直接沿用）：
        bull    → 66~80    neutral → 50    bear → 22~34
    有明确隔夜事件依据者在区间内 ±6 微调，再叠加观察池 -2 的池间差。
    """
    s = board[0]
    if s == 'bull':
        lo, hi = 66.0, 80.0
    elif s == 'bear':
        lo, hi = 22.0, 34.0
    else:
        lo, hi = 50.0, 50.0

    strong = e['sector'] in ('电池', '军工电子', '港口航运', '元件',
                             '光学光电子', '软件开发', '通信服务')
    mid = e['sector'] in ('房地产开发', '房地产服务', '电力', '光伏设备',
                          '风电设备', '建筑装饰', '医疗服务', '化学制药',
                          '生物制品', '轨交设备')
    if s == 'bull':
        d = (lo + hi) / 2 + (6 if strong else (3 if mid else 0))
    elif s == 'bear':
        d = (lo + hi) / 2 - (6 if strong else (3 if mid else 0))
    else:
        d = 50.0
    if pool == 'watching':
        d -= 2
    return int(max(18, min(86, round(d))))


def ensure_refs(e):
    """bearRefs/bullRefs 缺失时补全为结构化对象（脚本结构）。"""
    for k in ('bullRefs', 'bearRefs'):
        if not isinstance(e.get(k), list):
            e[k] = []


