def build_stocks(key):
    """按 POOL + NOTE_TAIL 生成 8 只 stocks 列表（顺序 龙头→概念→小盘→断板）。"""
    out = []
    for code, name, cat in POOL[key]:
        if cat == 'D':
            note = '断板反包·' + FORMS.get(code, '')
        else:
            prefix = {'L': '板块龙头', 'C': '相关概念', 'X': '小盘人气'}[cat]
            note = prefix + '·' + NOTE_TAIL[key].get(code, name)
        out.append({'code': code, 'name': name, 'note': note})
    return out


def imp(theme, key, horizon=None, direction=None):
    d = {'theme': theme, 'stocks': build_stocks(key)}
    if horizon:
        d['horizon'] = horizon
    return d


