def load():
    s = open(DATA_JS, encoding='utf-8').read()
    m = re.search(r'window\s*\.\s*DASHBOARD_DATA\s*=\s*(\{[\s\S]*\});?\s*$', s)
    if not m:
        raise SystemExit('data.js parse failed')
    return json.loads(m.group(1))


def save(D):
    open(DATA_JS, 'w', encoding='utf-8').write(
        PREFIX + json.dumps(D, ensure_ascii=False, separators=(',', ':')) + ';\n')


def blacklist():
    try:
        bl = json.load(open('risk_blacklist.json', encoding='utf-8'))
    except Exception:
        return set()
    out = set()
    for code, hit in (bl.get('blacklist') or {}).items():
        if (hit or {}).get('severity', 'red') == 'red':
            out.add(str(code))
    return out


