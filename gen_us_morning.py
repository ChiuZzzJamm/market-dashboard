def apply_reasons(us):
    norm = lambda s: re.sub(r'\s+', '', s or '')
    for key in ('sectorsUp', 'sectorsDown'):
        for sec in us.get(key, []):
            nm = norm(sec.get('name', ''))
            r = None
            for k, v in REASONS.items():
                if norm(k) == nm:
                    r = v
                    break
            if r:
                sec['reason'] = {'title': r['title'], 'detail': r['detail']}
                sec['deduce'] = r['ded']

